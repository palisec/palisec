#!/usr/bin/env node
/**
 * Writes the SellProbe runtime bytecode into apps/web/src/server/sell-probe.ts after `forge build`.
 * The probe is never deployed: the asset-safety simulation places it at the account as a state override.
 *   cd contracts && forge build && node script/export-probe.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const art = JSON.parse(readFileSync(new URL("../out/SellProbe.sol/SellProbe.json", import.meta.url), "utf8"));
const code = art.deployedBytecode.object;
const src = readFileSync(new URL("../src/SellProbe.sol", import.meta.url), "utf8").replace(/\r\n/g, "\n");
writeFileSync(
  new URL("../../apps/web/src/server/sell-probe.ts", import.meta.url),
  `// Generated by contracts/script/export-probe.mjs from contracts/src/SellProbe.sol. Do not edit.\n` +
    `/** SHA-256 of the Solidity source this bytecode was compiled from (solc 0.8.28, optimizer 200). */\n` +
    `export const SELL_PROBE_SOURCE_SHA256 = ${JSON.stringify(createHash("sha256").update(src).digest("hex"))};\n` +
    `export const SELL_PROBE_CODE = ${JSON.stringify(code)} as \`0x\${string}\`;\n`,
);
console.log(`sell probe: ${(code.length - 2) / 2} bytes`);
